def build(con, *, scorer_version: str, paired: bool) -> str:
    points = store.evaluation_points(con, scorer_version=scorer_version)
    elements = store.element_points(con, scorer_version=scorer_version)
    errors = store.element_errors(con, scorer_version=scorer_version)
    runs = store.run_evaluations(con)
    lead = store.lead_points(con, scorer_version=scorer_version)
    lead_err = store.lead_errors(con, scorer_version=scorer_version)
    all_runs = store.all_runs(con, producer_kind=None)

    if paired:
        # Every reader carries evaluation_id precisely so the subset is exact: filtering
        # a pre-aggregated table by station or subject would leave rows from evaluations
        # the subset excluded, and the section would quietly describe a different set
        # from the one in the header.
        keep = {r["evaluation_id"] for r in points if r["subject"] == "human"}
        points = [r for r in points if r["evaluation_id"] in keep]
        elements = [r for r in elements if r["evaluation_id"] in keep]
        errors = [r for r in errors if r["evaluation_id"] in keep]
        lead = [r for r in lead if r["evaluation_id"] in keep]
        lead_err = [r for r in lead_err if r["evaluation_id"] in keep]
        runs = [r for r in runs if r["evaluation_id"] in keep]

    model_pct = {r["evaluation_id"]: 100.0 * r["earned"] / r["available"]
                 for r in points if r["subject"] == "subject" and r["available"]}
    persist_pct = {r["evaluation_id"]: 100.0 * r["earned"] / r["available"]
                   for r in points if r["subject"] == "persistence" and r["available"]}

    windows = [r["valid_from"] for r in points if r.get("valid_from")]
    md = [
        "# Benchmark results", "",
        f"- generated: {datetime.utcnow():%Y-%m-%d %H:%MZ}",
        f"- scorer_version: **{scorer_version}**",
        f"- evaluations: **{len({r['evaluation_id'] for r in points})}**"
        f" ({'human-paired subset' if paired else 'all scored'})",
        f"- stations: {len({r['station'] for r in points})}",
    ]
    if windows:
        md.append(f"- window span: {min(windows):%Y-%m-%d %HZ} .. {max(windows):%Y-%m-%d %HZ}")
    md += ["", "All percentages pool points (sum earned / sum available). See the module",
           "docstring for why averaging per-evaluation percentages is not equivalent.", ""]

    md += section_headline(points, paired)
    md += section_gaps(points)
    md += section_elements(elements)
    md += section_stations(points)
    md += section_lead_time(lead, lead_err)
    md += section_orchestration(runs, model_pct, all_runs)
    md += section_tools(runs, model_pct, persist_pct)
    md += section_bias(errors)
    md += section_bias_by(errors)
    return "\n".join(md)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default=settings.db_path)
    ap.add_argument("--scorer-version", default=None,
                    help="default: the highest version present in the DB")
    ap.add_argument("--paired", action="store_true",
                    help="restrict to evaluations that also have a scored human TAF")
    ap.add_argument("--out", help="write the report here instead of stdout")
    args = ap.parse_args()

    con = store.connect(args.db, read_only=True)
    try:
        version = args.scorer_version
        if version is None:
            versions = store.scorer_versions(con)
            if not versions:
                print("no tafver_runs rows in this DB -- nothing to report", file=sys.stderr)
                return 1
            version = versions[-1]
        md = build(con, scorer_version=version, paired=args.paired)
    finally:
        con.close()

    if args.out:
        with open(args.out, "w") as fh:
            fh.write(md + "\n")
        print(f"wrote {args.out}")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
