def section_headline(points: list[dict], paired_only: bool) -> list[str]:
    """Pooled TAFVER per subject, plus the per-evaluation mean with its standard error
    (which IS the right way to put an uncertainty on a per-evaluation gap, even though
    it is the wrong way to compute the headline percentage itself)."""
    by_subject: dict[str, list[dict]] = defaultdict(list)
    for r in points:
        by_subject[r["subject"]].append(r)

    rows = []
    for name in sorted(by_subject, key=_subject_sort):
        rs = by_subject[name]
        pooled = pct(sum(r["earned"] for r in rs), sum(r["available"] for r in rs))
        per_eval = [100.0 * r["earned"] / r["available"] for r in rs if r["available"]]
        mean, se = _mean_se(per_eval)
        rows.append((name, len(rs), _f(pooled, 2), _f(mean, 2), _f(se, 2),
                     f"{sum(r['available'] for r in rs):,.0f}"))
    out = ["## Headline TAFVER", ""]
    out.append("Evaluation set: **human-paired subset**" if paired_only
               else "Evaluation set: **all scored evaluations**")
    out.append("")
    out += _table(rows, ["subject", "n evals", "pooled %", "mean-of-evals %", "SE", "opportunities"])
    out += ["`pooled %` is the reportable figure. `mean-of-evals %` is shown only so the",
            "difference between the two is visible; it is not the benchmark number.", ""]
    return out


def section_gaps(points: list[dict]) -> list[str]:
    """Paired per-evaluation gaps against the model, with a standard error. Restricted
    to evaluations where BOTH subjects scored, so a gap is never a composition artifact."""
    by_eval: dict[str, dict[str, float]] = defaultdict(dict)
    for r in points:
        if r["available"]:
            by_eval[r["evaluation_id"]][r["subject"]] = 100.0 * r["earned"] / r["available"]

    rows = []
    for other in sorted({s for v in by_eval.values() for s in v} - {"subject"}, key=_subject_sort):
        deltas = [v["subject"] - v[other] for v in by_eval.values()
                  if "subject" in v and other in v]
        mean, se = _mean_se(deltas)
        verdict = "--"
        if mean is not None and se:
            z = abs(mean) / se
            verdict = "resolved" if z >= 2 else "suggestive" if z >= 1 else "not resolved"
        rows.append((f"model - {other}", len(deltas), _signed(mean), _f(se, 2), verdict))
    return ["## Paired gaps vs the model", "",
            "Per-evaluation differences on evaluations where both subjects scored.",
            "`resolved` = |mean| >= 2 SE.", ""] + _table(
        rows, ["comparison", "n paired", "mean delta", "SE", "verdict"])


def section_elements(elements: list[dict]) -> list[str]:
    """Per-element pooled TAFVER, subjects side by side."""
    agg: dict[tuple[str, str], list[float]] = defaultdict(lambda: [0.0, 0.0])
    subjects: set[str] = set()
    for r in elements:
        cell = agg[(r["element"], r["subject"])]
        cell[0] += r["earned"]
        cell[1] += r["available"]
        subjects.add(r["subject"])
    ordered = sorted(subjects, key=_subject_sort)
    rows = []
    for el in sorted({k[0] for k in agg}):
        cells = [_f(pct(*agg[(el, s)])) if (el, s) in agg else "--" for s in ordered]
        best = None
        vals = {s: pct(*agg[(el, s)]) for s in ordered if (el, s) in agg}
        vals = {k: v for k, v in vals.items() if v is not None}
        if vals:
            best = max(vals, key=vals.get)
        rows.append((el, *cells, best or "--"))
    return ["## Per-element TAFVER", ""] + _table(rows, ["element", *ordered, "best"])


def section_stations(points: list[dict]) -> list[str]:
    """Per-station pooled TAFVER by subject. This is the difficulty-mining view: where
    persistence is high the regime is easy; where it is low but the human is high, human
    judgement is doing the work."""
    agg: dict[tuple[str, str], list[float]] = defaultdict(lambda: [0.0, 0.0])
    counts: dict[str, set] = defaultdict(set)
    subjects: set[str] = set()
    for r in points:
        cell = agg[(r["station"], r["subject"])]
        cell[0] += r["earned"]
        cell[1] += r["available"]
        subjects.add(r["subject"])
        if r["subject"] == "subject":
            counts[r["station"]].add(r["evaluation_id"])
    ordered = sorted(subjects, key=_subject_sort)
    rows = []
    for stn in sorted({k[0] for k in agg}):
        cells = [_f(pct(*agg[(stn, s)])) if (stn, s) in agg else "--" for s in ordered]
        rows.append((stn, len(counts.get(stn, ())), *cells))
    return ["## Per-station TAFVER", ""] + _table(rows, ["station", "n", *ordered])


def section_orchestration(runs: list[dict], model_pct: dict[str, float],
                          all_runs: list[dict]) -> list[str]:
    """Orchestration as a headline result, not a debugging aside: how many attempts
    produced a usable product, and at what process cost."""
    out = ["## Orchestration", "",
           "Per matrix cell, over evaluations that reached scoring:", ""]

    by_cell: dict[str, list[dict]] = defaultdict(list)
    for r in runs:
        by_cell[r.get("config_id") or "(no config_id)"].append(r)

    rows = []
    for cfg, rs in by_cell.items():
        scores = [model_pct[r["evaluation_id"]] for r in rs if r["evaluation_id"] in model_pct]
        mean, _ = _mean_se(scores)
        steps = [r["n_steps"] for r in rs if r["n_steps"] is not None]
        calls = [r["n_tool_calls"] for r in rs if r["n_tool_calls"] is not None]
        toks = [r["completion_tokens"] for r in rs if r["completion_tokens"] is not None]
        rows.append((CELL_NAMES.get(cfg, cfg), len(rs), _f(mean, 2),
                     _f(st.mean(steps) if steps else None),
                     _f(st.mean(calls) if calls else None),
                     f"{st.mean(toks):,.0f}" if toks else "--"))
    rows.sort(key=lambda r: (r[2] == "--", r[2]), reverse=True)
    out += _table(rows, ["cell", "n scored", "TAFVER", "steps", "tool calls", "out tokens"])

    out += ["Run outcomes over ALL runs, including those that never produced a scorable",
            "TAF. A clean-emit rate computed only over scored evaluations is survivorship:",
            "the runs that failed are exactly the ones that dropped out.", ""]
    by_model: dict[str, list[dict]] = defaultdict(list)
    for r in all_runs:
        by_model[r.get("model") or "(unknown)"].append(r)
    rows = []
    for model, rs in sorted(by_model.items(), key=lambda kv: -len(kv[1])):
        clean = sum(1 for r in rs if r.get("stop_reason") == "emitted_clean")
        fatal = sum(1 for r in rs if r.get("fatal"))
        no_emit = sum(1 for r in rs if not r.get("taf_id"))
        rows.append((model, len(rs), clean, _f(100.0 * clean / len(rs)), fatal, no_emit))
    out += _table(rows, ["model", "runs", "clean emits", "clean %", "fatal", "no TAF"])

    for field, title in (("stop_reason", "Stop reason"), ("convergence", "Convergence")):
        counts: dict[str, int] = defaultdict(int)
        for r in all_runs:
            counts[r.get(field) or "(null)"] += 1
        out += [f"{title}:", ""]
        out += _table(sorted(counts.items(), key=lambda kv: -kv[1]), [field.replace("_", " "), "runs"])
    return out


def section_tools(runs: list[dict], model_pct: dict[str, float],
                  persist_pct: dict[str, float]) -> list[str]:
    """Does tool use buy accuracy? Reported against a difficulty-controlled skill delta
    (model minus persistence on the SAME evaluation) as well as the raw score, because
    the raw view cannot distinguish 'more tools made it worse' from 'harder cases drew
    more tools'."""
    rec = []
    for r in runs:
        eid = r["evaluation_id"]
        if eid not in model_pct or r["n_tool_calls"] is None:
            continue
        rec.append({"calls": r["n_tool_calls"], "model": model_pct[eid],
                    "persist": persist_pct.get(eid), "cfg": r.get("config_id"),
                    "station": r["station"],
                    "tools": json.loads(r["tools_used_json"]) if r.get("tools_used_json") else {}})
    if not rec:
        return ["## Tool use vs accuracy", "", "(no runs with tool provenance)", ""]

    out = ["## Tool use vs accuracy", ""]
    with_p = [d for d in rec if d["persist"] is not None]
    if with_p:
        c_diff = _corr([d["calls"] for d in with_p], [d["persist"] for d in with_p])
        c_raw = _corr([d["calls"] for d in with_p], [d["model"] for d in with_p])
        c_skill = _corr([d["calls"] for d in with_p],
                        [d["model"] - d["persist"] for d in with_p])
        out += [f"- `corr(tool calls, persistence score)` = **{_signed(c_diff, 3)}** -- the "
                "confound check. Near zero means tool volume is not just tracking case difficulty.",
                f"- `corr(tool calls, model score)` = **{_signed(c_raw, 3)}**",
                f"- `corr(tool calls, model - persistence)` = **{_signed(c_skill, 3)}** -- the "
                "difficulty-controlled version.", ""]

    def _bin(c: int) -> str:
        return ("a. <=8" if c <= 8 else "b. 9-11" if c <= 11 else "c. 12-14"
                if c <= 14 else "d. 15-18" if c <= 18 else "e. 19+")

    rows = []
    for b in sorted({_bin(d["calls"]) for d in rec}):
        g = [d for d in rec if _bin(d["calls"]) == b]
        gp = [d for d in g if d["persist"] is not None]
        skill, se = _mean_se([d["model"] - d["persist"] for d in gp])
        rows.append((b, len(g), _f(st.mean([d["calls"] for d in g])),
                     _f(st.mean([d["model"] for d in g]), 2),
                     _f(st.mean([d["persist"] for d in gp]), 2) if gp else "--",
                     _signed(skill), _f(se, 2)))
    out += _table(rows, ["tool calls", "n", "mean calls", "model", "persistence",
                         "skill", "SE"])

    out += ["Per tool, pooled TAFVER of runs that used it vs runs that did not. Read with",
            "care: where a tool was withheld by the harness rather than declined by the",
            "model, this contrast IS the ablation, not a property of the tool.", ""]
    tools = sorted({t for d in rec for t in d["tools"]})
    rows = []
    for t in tools:
        w = [d["model"] for d in rec if t in d["tools"]]
        wo = [d["model"] for d in rec if t not in d["tools"]]
        mw, mwo = (st.mean(w) if w else None), (st.mean(wo) if wo else None)
        delta = None if (mw is None or mwo is None) else mw - mwo
        rows.append((t, len(w), _f(mw, 2), len(wo), _f(mwo, 2), _signed(delta)))
    rows.sort(key=lambda r: (r[5] == "--", -float(r[5]) if r[5] != "--" else 0))
    out += _table(rows, ["tool", "n with", "with", "n without", "without", "delta"])
    return out


def _lead_label(h: float) -> str:
    for lo, hi in LEAD_BINS:
        if lo <= h < hi:
            return f"{lo:02d}-{hi:02d}h"
    return f"{LEAD_BINS[-1][0]:02d}-{LEAD_BINS[-1][1]:02d}h"


def _slope(points: list[tuple[float, float]]) -> float | None:
    """Least-squares slope of y on x. Used for the per-cell degradation rate."""
    n = len(points)
    if n < 3:
        return None
    mx = sum(p[0] for p in points) / n
    my = sum(p[1] for p in points) / n
    den = sum((p[0] - mx) ** 2 for p in points)
    return None if den == 0 else sum((p[0] - mx) * (p[1] - my) for p in points) / den


def section_lead_time(lead: list[dict], lead_err: list[dict]) -> list[str]:
    """How accuracy decays from issue to the end of the validity window.

    This is where the naive floors earn their keep. Persistence is the best forecast
    available in the first few hours and then collapses; climatology, having no notion
    of when, is flat by construction and so doubles as an integrity check on the
    pipeline. The lead at which each floor is overtaken says more about where forecast
    value actually lives than any single combined number does."""
    out = ["## Lead-time degradation", "",
           "Pooled TAFVER by lead bin. `decay` is the last bin minus the first.", ""]

    combined: dict[tuple[str, str], list[float]] = defaultdict(lambda: [0.0, 0.0])
    for r in lead:
        c = combined[(r["subject"], _lead_label(r["lead_hr"]))]
        c[0] += r["earned"]
        c[1] += r["available"]
    subjects = sorted({k[0] for k in combined}, key=_subject_sort)
    labels = [f"{lo:02d}-{hi:02d}h" for lo, hi in LEAD_BINS]

    rows = []
    for lab in labels:
        cells = [_f(pct(*combined[(s, lab)])) if (s, lab) in combined else "--" for s in subjects]
        rows.append((lab, *cells))
    decay = []
    for s in subjects:
        first = combined.get((s, labels[0]))
        last = combined.get((s, labels[-1]))
        d = (None if not (first and last and first[1] and last[1])
             else pct(*last) - pct(*first))
        decay.append(_signed(d))
    rows.append(("**decay**", *decay))
    out += _table(rows, ["lead", *subjects])

    # Crossovers: the lead at which the model first overtakes each naive floor.
    for floor in ("persistence", "climo"):
        if not any(k[0] == floor for k in combined):
            continue
        crossed = None
        for lab in labels:
            a, b = combined.get(("subject", lab)), combined.get((floor, lab))
            if not (a and b and a[1] and b[1]):
                continue
            if pct(*a) > pct(*b):
                crossed = lab
                break
        out.append(f"- model first exceeds **{floor}** in the `{crossed}` bin."
                   if crossed else f"- model never exceeds **{floor}** at any lead.")
    out.append("")

    # Per element, model against the two references.
    per: dict[tuple[str, str, str], list[float]] = defaultdict(lambda: [0.0, 0.0])
    for r in lead:
        c = per[(r["element"], r["subject"], _lead_label(r["lead_hr"]))]
        c[0] += r["earned"]
        c[1] += r["available"]
    out += ["Per element. `m-p` is the model's margin over persistence -- it is the",
            "margin, not the level, that shows where forecast information is doing work.", ""]
    for el in sorted({k[0] for k in per}):
        rows = []
        for lab in labels:
            v = {s: (pct(*per[(el, s, lab)]) if (el, s, lab) in per else None)
                 for s in ("subject", "human", "persistence")}
            gap = (None if v["subject"] is None or v["persistence"] is None
                   else v["subject"] - v["persistence"])
            rows.append((lab, _f(v["subject"]), _f(v["human"]), _f(v["persistence"]),
                         _signed(gap, 1)))
        out += [f"**{el}**", ""] + _table(rows, ["lead", "model", "human", "persistence", "m-p"])

    # Un-thresholded errors for the elements where a tolerance band can mask drift.
    err: dict[tuple[str, str, str], list[float]] = defaultdict(lambda: [0.0, 0, 0.0])
    for r in lead_err:
        c = err[(r["element"], r["subject"], _lead_label(r["lead_hr"]))]
        c[0] += (r["mae"] or 0.0) * r["n_scored"]
        c[1] += r["n_scored"]
        c[2] += (r["bias"] or 0.0) * r["n_scored"]
    out += ["Continuous error, MAE (bias), for the elements a TAFVER tolerance band can",
            "hide drift behind. Units: ceiling ft, visibility SM, wind kt/degrees.", ""]
    for el in ("ceiling", "visibility", "wind_speed", "wind_dir"):
        if not any(k[0] == el for k in err):
            continue
        rows = []
        for lab in labels:
            cells = []
            for s in ("subject", "human", "persistence"):
                tot, n, b = err.get((el, s, lab), [0.0, 0, 0.0])
                nd = 0 if el == "ceiling" else 2
                cells.append(f"{tot/n:.{nd}f} ({b/n:+.{nd}f}) n={n}" if n else "--")
            rows.append((lab, *cells))
        out += [f"**{el}**", ""] + _table(rows, ["lead", "model", "human", "persistence"])

    # Aliasing guard: a lead bin that does not span the day cannot be read as a lead effect.
    hours: dict[str, dict[int, int]] = defaultdict(lambda: defaultdict(int))
    for r in lead:
        if r["subject"] == "subject" and r["obs_hour"] is not None:
            hours[_lead_label(r["lead_hr"])][int(r["obs_hour"])] += r["available"]
    rows = []
    for lab in labels:
        d = hours.get(lab)
        if not d:
            continue
        tot = sum(d.values())
        rows.append((lab, f"{tot:,}", len(d), _f(100.0 * max(d.values()) / tot) + "%"))
    out += ["Aliasing guard. With fixed issue cycles a given lead can always land on the",
            "same clock hour, which would make a diurnal effect look like a lead effect.",
            "A bin spanning all 24 hours with a low maximum share is not aliased.", ""]
    out += _table(rows, ["lead", "opportunities", "distinct hours-of-day", "largest hour share"])

    # Per-cell decay rate: two cells can share a mean and differ entirely in shape.
    cells_pts: dict[str, dict[float, list[float]]] = defaultdict(
        lambda: defaultdict(lambda: [0.0, 0.0]))
    for r in lead:
        if r["subject"] != "subject" or not r.get("config_id"):
            continue
        c = cells_pts[r["config_id"]][r["lead_hr"]]
        c[0] += r["earned"]
        c[1] += r["available"]
    rows = []
    for cfg, byl in cells_pts.items():
        pts = [(h, pct(*v)) for h, v in sorted(byl.items()) if v[1]]
        s = _slope(pts)
        early = [y for x, y in pts if x < 3]
        late = [y for x, y in pts if x >= 24]
        rows.append((CELL_NAMES.get(cfg, cfg), len(pts), _signed(10 * s) if s else "--",
                     _f(st.mean(early)) if early else "--",
                     _f(st.mean(late)) if late else "--"))
    rows.sort(key=lambda r: (r[2] == "--", -float(r[2]) if r[2] != "--" else 0))
    out += ["Decay rate per matrix cell, TAFVER points per 10h of lead. A cell can carry a",
            "good mean and a steep curve; the shape is a separate result from the level.", ""]
    out += _table(rows, ["cell", "lead points", "slope /10h", "0-3h", "24-30h"])
    return out


def section_bias(errors: list[dict]) -> list[str]:
    """Directional (signed) forecast bias per element. A scalar skill score hides
    systematic over- or under-forecasting entirely, and the sign is the actionable part."""
    agg: dict[tuple[str, str], dict] = {}
    for r in errors:
        k = (r["element"], r["subject"])
        a = agg.setdefault(k, {"bias_n": 0, "bias_sum": 0.0, "mae_sum": 0.0,
                               "scored": 0, "unavail": 0})
        a["scored"] += r["n_scored"] or 0
        a["unavail"] += r["n_unavailable"] or 0
        if r["bias"] is not None and r["n_scored"]:
            a["bias_sum"] += r["bias"] * r["n_scored"]
            a["mae_sum"] += (r["mae"] or 0.0) * r["n_scored"]
            a["bias_n"] += r["n_scored"]

    subjects = sorted({k[1] for k in agg}, key=_subject_sort)
    out = ["## Directional bias per element", "",
           "`bias` = mean(forecast - observed), pooled over scored hours. Ceiling in feet,",
           "visibility in statute miles, wind in knots/degrees. A NEGATIVE ceiling or",
           "visibility bias means the forecast was more restrictive than what verified.", "",
           "`coverage` is the share of hours where the element could be compared at all.",
           "Ceiling, visibility and gust are only defined when BOTH sides carried a finite",
           "value, so their bias describes the restricted subset -- not the whole window.", ""]
    rows = []
    for el in sorted({k[0] for k in agg}):
        for s in subjects:
            a = agg.get((el, s))
            if not a or not a["bias_n"]:
                continue
            total = a["scored"] + a["unavail"]
            cov = 100.0 * a["scored"] / total if total else None
            flag = " *" if el in CONDITIONAL_ELEMENTS else ""
            rows.append((el + flag, s, f"{a['bias_n']:,}", _f(cov),
                         _signed(a["bias_sum"] / a["bias_n"]),
                         _f(a["mae_sum"] / a["bias_n"], 2)))
    out += _table(rows, ["element", "subject", "n scored", "coverage %", "bias", "MAE"])
    out += ["`*` = conditional element; read the bias together with its coverage.", ""]
    return out


def section_bias_by(errors: list[dict], subject: str = "subject") -> list[str]:
    """Bias broken out by station for the forecast under test -- the view that shows
    whether a systematic error is global or belongs to one regime."""
    out = ["## Bias by station", ""]
    agg: dict[tuple[str, str], dict] = {}
    for r in errors:
        if r["subject"] != subject:
            continue
        a = agg.setdefault((r["element"], r["station"]), {"n": 0, "b": 0.0, "m": 0.0})
        if r["bias"] is not None and r["n_scored"]:
            a["n"] += r["n_scored"]
            a["b"] += r["bias"] * r["n_scored"]
            a["m"] += (r["mae"] or 0.0) * r["n_scored"]
    elements = sorted({k[0] for k in agg})
    stations = sorted({k[1] for k in agg})
    for el in elements:
        rows = []
        for stn in stations:
            a = agg.get((el, stn))
            if not a or not a["n"]:
                continue
            rows.append((stn, f"{a['n']:,}", _signed(a["b"] / a["n"]), _f(a["m"] / a["n"], 2)))
        rows.sort(key=lambda r: float(r[2]))
        out += [f"**{el}**", ""] + _table(rows, ["station", "n", "bias", "MAE"])
    return out


