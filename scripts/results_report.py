"""Read-only BENCHMARK RESULTS rollup -- the cross-evaluation counterpart to
score_taf.py (which reports one evaluation) and spend_report.py (which reports cost).

WHY THIS EXISTS. Every headline number this project has published so far came from
ad-hoc queries written fresh each session and thrown away. That has three costs: the
numbers are not reproducible, they drift between sessions, and the pooling rule is
re-implemented (or mis-implemented) every time. This script is the single place a
round's results are computed, so a figure in a write-up can be regenerated by name.

THE POOLING RULE, stated once and enforced here. A TAFVER percentage is
sum(points_earned) / sum(points_available) over the rows being combined -- points pool,
percentages never average. Averaging per-evaluation percentages over-weights short and
low-opportunity evaluations, and it does NOT bias every subject equally, so it distorts
the GAPS that the benchmark is actually claiming. On round 1 the mean-of-percentages
read inflates human by +0.64 and the model by +0.54 while leaving persistence flat
(+0.01) -- which shrinks the model-over-persistence margin from +1.55 to +1.00.

SCORER VERSION. The result tables are append-only and keyed on scorer_version, so a
rescored DB holds v1 and v2 rows for the same evaluation. Reading without a version
filter silently pools two scorers. This script requires a version (default: the highest
present) and prints it in the provenance header.

No LLM, no network, no writes. Safe against a live DB (read-only connection).

Usage:
    uv run python scripts/results_report.py [--db PATH] [--scorer-version 2]
    uv run python scripts/results_report.py --paired          # human-comparable subset
    uv run python scripts/results_report.py --out logs/results_round1.md
"""

