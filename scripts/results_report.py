# Matrix cells carry a hashed config_id; these are round 1's, resolved to readable
# names. An unknown hash prints as-is rather than being dropped.
CELL_NAMES: dict[str, str] = {
    "cfg_ab651bfa79bf": "MiniMax control",
    "cfg_14dce8e60207": "MiniMax temp0.2",
    "cfg_2d6a267af6bb": "MiniMax no-worksheet",
    "cfg_5b4c79c2fe18": "MiniMax no-prior-TAF",
    "cfg_8bec75a8894f": "Gemma control",
    "cfg_6971cd5c60f3": "Kimi control",
}

# Subjects in canonical reporting order: the forecast under test, then the human
# reference, then the naive floors it must clear.
SUBJECT_ORDER = ["subject", "human", "human_composite", "persistence", "climo"]

# Elements whose bias is only defined on hours where BOTH sides carried a finite
# value; their coverage fraction is reported alongside so a bias is never read bare.
CONDITIONAL_ELEMENTS = {"ceiling", "visibility", "wind_gust"}

# Lead-time bins, hours from valid_from. 3h through +24h, then one wider tail bin --
# a 30h TAF has only 6 hours beyond +24 and they would otherwise be too thin to read.
LEAD_BINS = [(0, 3), (3, 6), (6, 9), (9, 12), (12, 15), (15, 18), (18, 21), (21, 24), (24, 30)]


def pct(earned: float, available: float) -> float | None:
    """The pooling rule. None when nothing was available (never 0.0, which would read
    as a real score of zero)."""
    return None if not available else 100.0 * earned / available


def _f(v, nd: int = 1, dash: str = "--") -> str:
    return dash if v is None else f"{v:.{nd}f}"


def _signed(v, nd: int = 2, dash: str = "--") -> str:
    return dash if v is None else f"{v:+.{nd}f}"


def _table(rows: list[tuple], cols: list[str], align_right: set[int] | None = None) -> list[str]:
    """A markdown table. Empty row list yields an explicit '(none)' line so a section
    never silently disappears."""
    if not rows:
        return ["(none)", ""]
    right = align_right or set(range(1, len(cols)))
    out = ["| " + " | ".join(cols) + " |",
           "|" + "|".join("---:" if i in right else "---" for i in range(len(cols))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    out.append("")
    return out


def _mean_se(values: list[float]) -> tuple[float | None, float | None]:
    if not values:
        return None, None
    if len(values) == 1:
        return values[0], None
    return st.mean(values), st.stdev(values) / math.sqrt(len(values))


def _corr(xs: list[float], ys: list[float]) -> float | None:
    n = len(xs)
    if n < 3:
        return None
    mx, my = sum(xs) / n, sum(ys) / n
    num = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    dx = math.sqrt(sum((x - mx) ** 2 for x in xs))
    dy = math.sqrt(sum((y - my) ** 2 for y in ys))
    return None if dx * dy == 0 else num / (dx * dy)


def _subject_sort(name: str) -> tuple[int, str]:
    return (SUBJECT_ORDER.index(name), "") if name in SUBJECT_ORDER else (len(SUBJECT_ORDER), name)


